"""Writes the generated Max patches, and creates the hand-built ones once.

Everything Max loads lives directly in patchers/, next to canon.maxpat: on a
fresh clone Max doesn't look in subfolders or follow relative paths (M0 spike
a, PLAN.md 2.2). So every patch, abstraction and bundle has a bare name.

Patch authoring is hybrid (PLAN.md 4.4):

  GENERATED  wiring-heavy abstractions (M0's spike patches were too, until M0
             closed; they're in git history). This script is
             their master copy: change them here, run it, commit both. A change
             made in Max is lost the next time this runs. CI runs --check.
  HAND       the main patch and the UI panels. --init creates each one only if
             it doesn't exist yet; after that they belong to you and Max, and
             this script never touches them again.

    python3 tools/patchgen.py           write the generated patches
    python3 tools/patchgen.py --check   exit 1 if a generated patch would change
    python3 tools/patchgen.py --init    also create missing hand-built patches
    python3 tools/patchgen.py --list    print both lists as JSON (for the tests)

Python's standard library only. Development only: it isn't part of what ships.
The Patch class is ported from nnokes/cento's tools/maxgen.py (MIT).
"""
