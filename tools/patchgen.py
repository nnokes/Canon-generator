def write_generated(path, text):
    full = REPO / path
    raw = text.encode("utf-8")
    if CHECK:
        if not full.exists() or full.read_bytes() != raw:
            STALE.append(path)
        return
    if full.exists() and full.read_bytes() == raw:
        return
    full.parent.mkdir(parents=True, exist_ok=True)
    full.write_bytes(raw)
    print("wrote", path)


def create_hand(path, text):
    full = REPO / path
    if full.exists():
        return
    full.parent.mkdir(parents=True, exist_ok=True)
    full.write_bytes(text.encode("utf-8"))
    print("created", path, "(hand-built from now on)")


def main():
    if "--list" in ARGS:
        print(json.dumps({"generated": sorted(GENERATED), "hand": sorted(HAND),
                          "generated_note": GENERATED_NOTE, "hand_note": HAND_NOTE}))
        return
    assert not set(GENERATED) & set(HAND), "a patch can't be both generated and hand-built"
    for path, build in GENERATED.items():
        write_generated(path, build().to_json())
    if INIT and not CHECK:
        for path, build in HAND.items():
            create_hand(path, build().to_json())
    if CHECK:
        if STALE:
            print("generated patches differ from tools/patchgen.py (run npm run patches, "
                  "or move your Max edits into the generator):")
            for path in STALE:
                print("  " + path)
            sys.exit(1)
        print("generated patches are up to date")


if __name__ == "__main__":
    main()
