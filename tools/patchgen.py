"""Writes the generated Max patches, and creates the hand-built ones once.

Everything Max loads lives directly in patchers/, next to canon.maxpat: on a
fresh clone Max doesn't look in subfolders or follow relative paths (M0 spike
a, PLAN.md 2.2). So every patch, abstraction and bundle has a bare name.

Patch authoring is hybrid (PLAN.md 4.4):

  GENERATED  wiring-heavy abstractions and the M0 spike patches. This script is
             their master copy: change them here, run it, commit both. A change
             made in Max is lost the next time this runs. CI runs --check.
  HAND       the main patch and the UI panels. --init creates each one only if
             it doesn't exist yet; after that they belong to you and Max, and
             this script never touches them again.

    python3 tools/patchgen.py           write the generated patches
    python3 tools/patchgen.py --check   exit 1 if a generated patch would change
    python3 tools/patchgen.py --init    also create missing hand-built patches
    python3 tools/patchgen.py --list    print both lists as JSON (for the tests)

Python's standard library only. Development only: it isn't part of what ships.
The Patch class is ported from nnokes/cento's tools/maxgen.py (MIT).
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ARGS = sys.argv[1:]
CHECK = "--check" in ARGS
INIT = "--init" in ARGS
STALE = []  # --check: the generated files that would change
APPVERSION = {"major": 9, "minor": 0, "revision": 7, "architecture": "x64", "modernui": 1}

GENERATED_NOTE = ("GENERATED by tools/patchgen.py: don't edit this patch in Max. "
                  "Change the generator, then run: npm run patches")
HAND_NOTE = ("Hand-built: created once by tools/patchgen.py --init. "
             "It's yours now: edit it freely in Max; the generator never overwrites it.")


class Patch:
    def __init__(self, rect=(80, 80, 900, 620), presentation=False):
        self.rect = rect
        self.presentation = presentation
        self.boxes = []
        self.lines = []
        self.n = 0

    def _add(self, box):
        self.n += 1
        box["id"] = f"obj-{self.n}"
        self.boxes.append({"box": box})
        return box["id"]

    def _place(self, box, x, y, w, h):
        box["patching_rect"] = [float(x), float(y), float(w), float(h)]
        return box

    def obj(self, text, x, y, ins, outs, outtypes=None, w=None, **extra):
        w = w or max(40, 7 * len(text) + 14)
        box = {
            "maxclass": "newobj",
            "text": text,
            "numinlets": ins,
            "numoutlets": outs,
            "outlettype": outtypes if outtypes is not None else [""] * outs,
        }
        if text.startswith("v8 "):
            box["textfile"] = {"filename": text.split()[1], "flags": 0, "embed": 0, "autowatch": 1}
        box.update(extra)
        return self._add(self._place(box, x, y, w, 22))

    def msg(self, text, x, y, w=None):
        w = w or max(30, 7 * len(text) + 16)
        box = {"maxclass": "message", "text": text, "numinlets": 2, "numoutlets": 1, "outlettype": [""]}
        return self._add(self._place(box, x, y, w, 22))

    def comment(self, text, x, y, w=None, h=20, **extra):
        w = w or max(30, 6.5 * len(text) + 10)
        box = {"maxclass": "comment", "text": text, "numinlets": 1, "numoutlets": 0}
        box.update(extra)
        return self._add(self._place(box, x, y, w, h))

    def note(self, text, x, y, w, lines):
        """A wrapped comment of `lines` lines."""
        return self.comment(text, x, y, w=w, h=14 + 14 * lines, linecount=lines)

    def ui(self, maxclass, x, y, w, h, ins, outs, outtypes, **extra):
        box = {"maxclass": maxclass, "numinlets": ins, "numoutlets": outs, "outlettype": outtypes}
        box.update(extra)
        return self._add(self._place(box, x, y, w, h))

    def inlet(self, x, y, comment, index):
        box = {"maxclass": "inlet", "comment": comment, "index": index, "numinlets": 0,
               "numoutlets": 1, "outlettype": [""]}
        return self._add(self._place(box, x, y, 30, 30))

    def outlet(self, x, y, comment, index):
        box = {"maxclass": "outlet", "comment": comment, "index": index, "numinlets": 1, "numoutlets": 0}
        return self._add(self._place(box, x, y, 30, 30))

    def bpatcher(self, name, x, y, w, h, ins, outs):
        box = {
            "maxclass": "bpatcher", "name": name, "numinlets": ins, "numoutlets": outs,
            "outlettype": [""] * outs, "offset": [0.0, 0.0], "viewvisibility": 1,
            "bgmode": 0, "border": 1, "clickthrough": 0, "enablehscroll": 0,
            "enablevscroll": 0, "lockeddragscroll": 0,
        }
        return self._add(self._place(box, x, y, w, h))

    def connect(self, src, outlet, dst, inlet):
        self.lines.append({"patchline": {"source": [src, outlet], "destination": [dst, inlet]}})

    def to_json(self):
        p = {
            "fileversion": 1,
            "appversion": APPVERSION,
            "classnamespace": "box",
            "rect": [float(v) for v in self.rect],
            "openinpresentation": 1 if self.presentation else 0,
            "default_fontsize": 12.0,
            "default_fontface": 0,
            "default_fontname": "Arial",
            "gridonopen": 1,
            "gridsize": [15.0, 15.0],
            "gridsnaponopen": 1,
            "objectsnaponopen": 1,
            "statusbarvisible": 2,
            "toolbarvisible": 1,
            "boxes": self.boxes,
            "lines": self.lines,
        }
        return json.dumps({"patcher": p}, indent="\t", ensure_ascii=True) + "\n"


