def engine():
    """cg.engine: the engine's [v8] wrappers. So far only hello."""
    p = Patch(rect=(120, 120, 520, 300))
    p.note(GENERATED_NOTE, 20, 10, 470, 2)
    p.comment("cg.engine: hello -> hello <name> <version> seed <n> check <a b c d> note <midi> <hz>", 20, 55)
    inl = p.inlet(20, 80, "messages for the engine: hello", 0)
    route = p.obj("route hello", 20, 125, 2, 2)
    hello = p.obj("v8 cg.hello.bundle.js", 20, 165, 1, 1)
    out = p.outlet(20, 215, "engine replies, each starting with a selector", 0)
    p.connect(inl, 0, route, 0)
    p.connect(route, 0, hello, 0)
    p.connect(hello, 0, out, 0)
    return p


def tuning():
    """cg.tuning (M1): the scale-system engine with an audition voice that
    measures itself. Inlet: messages (see code/cg.tuning.v8.js). Outlet 0: the
    engine's other messages, selector first (menu, readout, runmax, cents,
    status, error). Outlet 1: the voice's signal."""
    p = Patch(rect=(100, 100, 640, 520))
    p.note(GENERATED_NOTE, 20, 10, 600, 2)
    p.note("cg.tuning: scale systems and an audition voice. In: starter, system, load, mode, ref, play, "
           "key, hold, silence, info. Out (left): menu, readout, runmax, cents, status, error. "
           "Out (right): the voice. [fzero~] measures the voice; every 10 readings a cents summary "
           "comes out as status.", 20, 55, 600, 3)
    inl = p.inlet(20, 115, "messages: starter, system, load, mode, ref, play, key, hold, silence, info", 0)
    # On load: fill the chooser, then pick the first starter.
    load = p.obj("loadbang", 120, 115, 1, 1, ["bang"])
    order = p.obj("t b b", 120, 145, 1, 2, ["bang", "bang"])
    fill = p.msg("starters", 200, 175)
    first = p.msg("starter 0", 120, 175)
    v8 = p.obj("v8 cg.tuning.bundle.js", 20, 215, 1, 1)
    route = p.obj("route freq amp", 20, 255, 2, 3)
    p.connect(inl, 0, v8, 0)
    p.connect(load, 0, order, 0)
    p.connect(order, 1, fill, 0)
    p.connect(order, 0, first, 0)
    p.connect(fill, 0, v8, 0)
    p.connect(first, 0, v8, 0)
    p.connect(v8, 0, route, 0)

    # The voice: a sine at the exact frequency; its gain always ramps (no clicks).
    osc = p.obj("cycle~", 20, 300, 2, 1, ["signal"])
    ramp = p.obj("line~", 120, 300, 2, 2, ["signal", "bang"])
    gain = p.obj("*~", 20, 340, 2, 1, ["signal"])
    p.connect(route, 0, osc, 0)
    p.connect(route, 1, ramp, 0)
    p.connect(osc, 0, gain, 0)
    p.connect(ramp, 0, gain, 1)

    # It measures itself: the fundamental goes back to the script.
    tracker = p.obj("fzero~", 300, 340, 1, 3, ["float", "float", "bang"])
    limit = p.obj("speedlim 500", 300, 375, 2, 1)
    measured = p.obj("prepend measuredhz", 300, 410, 2, 1)
    p.connect(gain, 0, tracker, 0)
    p.connect(tracker, 0, limit, 0)
    p.connect(limit, 0, measured, 0)
    p.connect(measured, 0, v8, 0)

    # Max numbers outlets by position, left to right: messages left, signal right.
    out_messages = p.outlet(20, 460, "menu, readout, runmax, cents, status, error", 0)
    out_signal = p.outlet(200, 460, "the voice (signal)", 1)
    p.connect(route, 2, out_messages, 0)
    p.connect(gain, 0, out_signal, 0)
    return p


def voice():
    """cg.voice~ (M2): one voice of the [poly~ cg.voice~] bank. Four harmonic
    partials whose weights are a parameter, an envelope that is one [line~]
    list, and a stereo gain pair. Messages arrive through [in 1] ([poly~]'s "note"
    message gives the first free voice the rest of the message, without "note"):
      <hz> <gain L> <gain R> <total ms> <envelope pairs...>   a note
      partials <w1> <w2> <w3> <w4>
      stop
    It marks itself busy for the note's length, timed by Max (not JS)."""
    p = Patch(rect=(120, 120, 760, 560))
    p.note(GENERATED_NOTE, 20, 10, 700, 1)
    p.note("cg.voice~: one voice of the canon's [poly~] voice bank. A list 'hz gainL gainR totalms envelope...' "
           "plays a note ([poly~] strips the word 'note'); 'partials w1 w2 w3 w4' sets the weights of partials 1-4; "
           "'stop' fades out.", 20, 40, 700, 2)
    inp = p.obj("in 1", 20, 85, 0, 1)
    route = p.obj("route partials stop", 20, 115, 2, 3)
    p.connect(inp, 0, route, 0)

    # A note: busy now; split the head (hz, gains, length) from the envelope.
    order = p.obj("t l b", 20, 150, 1, 2, ["", "bang"])
    busy_on = p.msg("1", 120, 180)
    voice_state = p.obj("thispoly~", 120, 470, 1, 2, ["int", "int"])
    head = p.obj("zl slice 4", 20, 180, 2, 2)
    fields = p.obj("unpack f f f f", 20, 210, 1, 4, ["float", "float", "float", "float"])
    env = p.obj("line~", 330, 210, 2, 2, ["signal", "bang"])
    p.connect(route, 2, order, 0)
    p.connect(order, 1, busy_on, 0)
    p.connect(busy_on, 0, voice_state, 0)
    p.connect(order, 0, head, 0)
    p.connect(head, 0, fields, 0)
    p.connect(head, 1, env, 0)

    # Free again once the note is over.
    free_after = p.obj("delay", 230, 410, 2, 1, ["bang"])
    busy_off = p.msg("0", 230, 440)
    p.connect(fields, 3, free_after, 0)
    p.connect(free_after, 0, busy_off, 0)
    p.connect(busy_off, 0, voice_state, 0)

    # Partials 1-4 of the note's frequency, weighted (defaults sum to 1).
    split = p.obj("t f f f f", 20, 245, 1, 4, ["float", "float", "float", "float"])
    p.connect(fields, 0, split, 0)
    weights = p.obj("unpack f f f f", 440, 115, 1, 4, ["float", "float", "float", "float"])
    defaults = p.msg(" ".join(f"{w:g}" for w in PARTIALS), 560, 85)
    start = p.obj("loadbang", 440, 85, 1, 1, ["bang"])
    p.connect(route, 0, weights, 0)
    p.connect(start, 0, defaults, 0)
    p.connect(defaults, 0, weights, 0)
    partials = []
    for k in range(4):
        x = 20 + 110 * k
        if k == 0:
            src = split
            src_outlet = 3
        else:
            src = p.obj(f"* {k + 1}.", x, 275, 2, 1, ["float"])
            p.connect(split, 3 - k, src, 0)
            src_outlet = 0
        osc = p.obj("cycle~", x, 305, 2, 1, ["signal"])
        p.connect(src, src_outlet, osc, 0)
        weight = p.obj(f"*~ {PARTIALS[k]:g}", x, 335, 2, 1, ["signal"])
        p.connect(osc, 0, weight, 0)
        p.connect(weights, k, weight, 1)
        partials.append(weight)
    sum1 = p.obj("+~", 20, 365, 2, 1, ["signal"])
    sum2 = p.obj("+~", 240, 365, 2, 1, ["signal"])
    total = p.obj("+~", 20, 395, 2, 1, ["signal"])
    p.connect(partials[0], 0, sum1, 0)
    p.connect(partials[1], 0, sum1, 1)
    p.connect(partials[2], 0, sum2, 0)
    p.connect(partials[3], 0, sum2, 1)
    p.connect(sum1, 0, total, 0)
    p.connect(sum2, 0, total, 1)

    # Envelope, then the stereo gains.
    shaped = p.obj("*~", 20, 425, 2, 1, ["signal"])
    p.connect(total, 0, shaped, 0)
    p.connect(env, 0, shaped, 1)
    left = p.obj("*~", 20, 455, 2, 1, ["signal"])
    right = p.obj("*~", 70, 455, 2, 1, ["signal"])
    p.connect(shaped, 0, left, 0)
    p.connect(shaped, 0, right, 0)
    p.connect(fields, 1, left, 1)
    p.connect(fields, 2, right, 1)
    out_left = p.obj("out~ 1", 20, 495, 1, 0)
    out_right = p.obj("out~ 2", 90, 495, 1, 0)
    p.connect(left, 0, out_left, 0)
    p.connect(right, 0, out_right, 0)

    # stop: fade out, cancel the busy timer, free the voice.
    halt = p.obj("t b b", 560, 150, 1, 2, ["bang", "bang"])
    fade = p.msg("0 30", 560, 180)
    cancel = p.msg("stop", 640, 180)
    p.connect(route, 1, halt, 0)
    p.connect(halt, 1, fade, 0)
    p.connect(fade, 0, env, 0)
    p.connect(halt, 0, cancel, 0)
    p.connect(cancel, 0, free_after, 0)
    p.connect(halt, 0, busy_off, 0)
    return p


def mpe_out():
    """cg.mpe.out (M2): MPE notes as raw MIDI bytes. In:
      <dur ms> <bend + note-on: 6 bytes> <note-off: 3 bytes>   a note
      midi <bytes...>                                          bytes now (the zone setup)
      panic                                                    all notes off, channels 2-16
    The note-off is delayed by Max ([pipe], by the note's own length), not JS.
    Out: the bytes, one at a time, for [midiout] or a synth that takes them."""
    p = Patch(rect=(140, 140, 640, 440))
    p.note(GENERATED_NOTE, 20, 10, 600, 1)
    p.note("cg.mpe.out: a note list 'ms, 6 on-bytes, 3 off-bytes' plays now and [pipe] sends its note-off "
           "after its length. 'midi bytes' go straight out; 'panic' stops every note.", 20, 40, 600, 2)
    inlet = p.inlet(20, 85, "notes (ms + 9 bytes), midi <bytes>, panic", 0)
    route = p.obj("route midi panic", 20, 120, 2, 3)
    p.connect(inlet, 0, route, 0)
    out = p.obj("iter", 20, 380, 1, 1, ["int"])
    p.connect(route, 0, out, 0)

    # panic: clear the pending note-offs, then all notes off on every member channel.
    halt = p.obj("t b b", 140, 155, 1, 2, ["bang", "bang"])
    clear = p.msg("clear", 230, 190)
    off_all = p.msg(" ".join(f"{0xB0 + ch} 123 0" for ch in range(1, 16)), 140, 345, w=330)
    p.connect(route, 1, halt, 0)
    p.connect(halt, 1, clear, 0)
    p.connect(halt, 0, off_all, 0)
    p.connect(off_all, 0, out, 0)

    # A note: its length to [pipe]'s delay first (right to left), then the bytes.
    order = p.obj("t l l", 330, 155, 1, 2, ["", ""])
    length = p.obj("zl slice 1", 430, 190, 2, 2)
    bytes_ = p.obj("zl slice 1", 330, 190, 2, 2)
    on_off = p.obj("zl slice 6", 330, 225, 2, 2)
    later = p.obj("pipe 0 0 0 0", 430, 265, 4, 3, ["int", "int", "int"])
    again = p.obj("pack i i i", 430, 300, 3, 1)
    p.connect(route, 2, order, 0)
    p.connect(order, 1, length, 0)
    p.connect(length, 0, later, 3)
    p.connect(order, 0, bytes_, 0)
    p.connect(bytes_, 1, on_off, 0)
    p.connect(on_off, 1, later, 0)
    p.connect(on_off, 0, out, 0)
    p.connect(clear, 0, later, 0)
    for k in range(3):
        p.connect(later, k, again, k)
    p.connect(again, 0, out, 0)
    outlet = p.outlet(20, 410, "MIDI bytes, one at a time", 0)
    p.connect(out, 0, outlet, 0)
    return p


def canon():
    """cg.canon (M2): the renderer, its player and the voices. Inlet: messages
    (see code/cg.canon.v8.js), plus play and stop. Outlet 0: the engine's other
    messages (menu, tmenu, bpm, editor, status, error, melody). Outlets 1 and 2:
    left and right audio: the [poly~] Hz voices plus Ableton's Drift playing
    the MPE notes. Outlet 3: the MPE notes as MIDI bytes, for the panel's
    [midiout]. MPE goes to Drift or to MIDI out, never both ([gate 2]).
    [r cg.canon.in] takes the same messages as the inlet, from elsewhere: the
    answer finder sends stop, usespec cg.audition, then play (M3)."""
    p = Patch(rect=(80, 80, 900, 720))
    p.note(GENERATED_NOTE, 20, 10, 700, 1)
    inl = p.obj("route play stop", 20, 115, 2, 3)
    inlet = p.inlet(20, 85, "messages: preset, tuning, tempo, render, select, edits, output, loadmidi, loadspec, "
                    "savespec, play, stop", 0)
    p.connect(inlet, 0, inl, 0)
    load = p.obj("loadbang", 430, 85, 1, 1, ["bang"])
    order = p.obj("t b b b", 430, 115, 1, 3, ["bang", "bang", "bang"])
    fill = p.msg("presets", 600, 145)
    fill_tunings = p.msg("tunings", 520, 145)
    first = p.msg("preset 0", 430, 145)
    v8 = p.obj("v8 cg.canon.bundle.js", 230, 185, 1, 1)
    p.connect(load, 0, order, 0)
    p.connect(order, 2, fill, 0)
    p.connect(order, 1, fill_tunings, 0)
    p.connect(order, 0, first, 0)
    for m in (fill, fill_tunings, first):
        p.connect(m, 0, v8, 0)
    p.connect(inl, 2, v8, 0)
    # Messages from elsewhere (the answer finder: stop, usespec cg.audition, play)
    # go where the inlet's go, so play and stop work too (M3).
    audition = p.obj("r cg.canon.in", 230, 150, 1, 1)
    p.connect(audition, 0, inl, 0)
    route = p.obj("route coll midi mpeto panic", 230, 220, 2, 5)
    p.connect(v8, 0, route, 0)

    # The player: index -> [coll] row -> play the note, wait the delay, next index.
    play = p.obj("t b b", 20, 150, 1, 2, ["bang", "bang"])
    zero = p.msg("0", 110, 180)
    start = p.obj("delay 100", 20, 180, 2, 1, ["bang"])
    index = p.obj("i", 20, 260, 2, 1, ["int"])
    step = p.obj("t i i", 20, 290, 1, 2, ["int", "int"])
    nxt = p.obj("+ 1", 110, 290, 2, 1, ["int"])
    queue = p.obj("coll", 230, 320, 1, 4, ["", "", "", "bang"])
    head = p.obj("zl slice 1", 230, 355, 2, 2)
    gate = p.obj("if $f1 >= 0. then $f1", 20, 390, 1, 1)
    wait = p.obj("delay", 20, 420, 2, 1, ["bang"])
    kind = p.obj("route mpe", 330, 390, 2, 2)
    note = p.obj("prepend note", 330, 420, 2, 1)
    bank = p.obj("poly~ cg.voice~ 32", 330, 455, 1, 2, ["signal", "signal"])
    p.connect(inl, 0, play, 0)
    p.connect(play, 1, zero, 0)
    p.connect(zero, 0, index, 1)
    p.connect(play, 0, start, 0)
    p.connect(start, 0, index, 0)
    p.connect(index, 0, step, 0)
    p.connect(step, 1, nxt, 0)
    p.connect(nxt, 0, index, 1)
    p.connect(step, 0, queue, 0)
    p.connect(route, 0, queue, 0)
    p.connect(queue, 0, head, 0)
    p.connect(head, 0, gate, 0)
    p.connect(gate, 0, wait, 0)
    p.connect(wait, 0, index, 0)
    p.connect(head, 1, kind, 0)
    p.connect(kind, 1, note, 0)
    p.connect(note, 0, bank, 0)

    # MPE: rows marked "mpe" (and the zone setup) to cg.mpe.out, then through
    # [gate 2] to one destination: Drift inside Max (second oscillator on, no
    # random detune), or outlet 3 for the panel's [midiout]. "mpeto" sets it.
    zone = p.obj("prepend midi", 360, 255, 2, 1)
    mpe = p.obj("cg.mpe.out", 560, 420, 1, 1, ["int"])
    p.connect(route, 1, zone, 0)
    p.connect(zone, 0, mpe, 0)
    p.connect(kind, 0, mpe, 0)
    where = p.obj("gate 2 1", 560, 460, 2, 2)
    p.connect(route, 2, where, 0)
    p.connect(mpe, 0, where, 1)
    drift = p.obj("abl.device.drift~ @drift 0", 650, 460, 1, 2, ["signal", "signal"])
    p.connect(where, 0, drift, 0)
    drift_left = p.obj("*~ 0.3", 650, 495, 2, 1, ["signal"])
    drift_right = p.obj("*~ 0.3", 720, 495, 2, 1, ["signal"])
    p.connect(drift, 0, drift_left, 0)
    p.connect(drift, 1, drift_right, 0)
    left = p.obj("+~", 330, 535, 2, 1, ["signal"])
    right = p.obj("+~", 430, 535, 2, 1, ["signal"])
    p.connect(bank, 0, left, 0)
    p.connect(drift_left, 0, left, 1)
    p.connect(bank, 1, right, 0)
    p.connect(drift_right, 0, right, 1)

    # stop: halt the chain, fade every Hz voice, and stop every MPE note.
    halt = p.obj("t b b", 160, 115, 1, 2, ["bang", "bang"])
    stop_chain = p.msg("stop", 160, 220)
    stop_voices = p.msg("target 0, stop", 470, 390)
    panic = p.msg("panic", 600, 390)
    p.connect(inl, 1, halt, 0)
    p.connect(halt, 1, stop_chain, 0)
    p.connect(stop_chain, 0, start, 0)
    p.connect(stop_chain, 0, wait, 0)
    p.connect(halt, 0, stop_voices, 0)
    p.connect(stop_voices, 0, bank, 0)
    p.connect(halt, 0, panic, 0)
    p.connect(route, 3, panic, 0)  # the script's panic, before a change of destination
    p.connect(panic, 0, mpe, 0)

    # Outlets left to right: messages, left audio, right audio, MPE MIDI bytes.
    out_messages = p.outlet(230, 580, "menu, tmenu, bpm, editor, status, error, melody", 0)
    out_left = p.outlet(330, 580, "left audio", 1)
